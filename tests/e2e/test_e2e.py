results, failures, timings = [], [], {}

def check(name, cond, detail=''):
    results.append((name, bool(cond), detail))
    if not cond: failures.append(f'{name}: {detail}')
    print(('PASS ' if cond else 'FAIL ') + name + (f'  [{detail}]' if detail and not cond else ''))

def new_page(b, **kw):
    pg = b.new_page(**kw)
    pg.errors = []
    pg.on('pageerror', lambda e: pg.errors.append(str(e)))
    pg.on('console', lambda m: pg.errors.append(m.text) if m.type == 'error' and 'Failed to load resource' not in m.text else None)
    return pg

def boot(pg):
    t0 = time.time(); pg.goto(PAGE)
    pg.wait_for_function("document.getElementById('stMsg').textContent !== 'Starting the simulator…' && document.getElementById('stMsg').textContent !== ''", timeout=60000)
    return time.time() - t0

def msg(pg): return pg.inner_text('#stMsg')
def sim_t(pg):
    m = re.search(r'Tran:\s*(-?[\d.]+)\s*([mµun]?)s', pg.inner_text('#stSim'))
    return float(m.group(1)) * {'': 1, 'm': 1e-3, 'µ': 1e-6, 'u': 1e-6, 'n': 1e-9}[m.group(2)] if m else None
def tabs(pg): return pg.eval_on_selector_all('#designTabs [role=tab]', 'ts => ts.map(t => t.title)')
def wins(pg): return pg.eval_on_selector_all('.win .ttl', 'ts => ts.map(t => t.textContent)')
def win(pg, title): return pg.locator('.win', has=pg.locator('.ttl', has_text=title)).first
def open_files(pg, names):
    pg.set_input_files('#file', [str(FIX / (n + '.ms14')) for n in names])
    pg.wait_for_function('n => [...document.querySelectorAll("#designTabs [role=tab]")].some(t => t.title === n)', arg=names[-1], timeout=60000)
    pg.wait_for_timeout(200)
def menu(pg, top, *path):
    pg.click(f'#menubar > button:text-is("{top}")')
    for i, label in enumerate(path):
        item = pg.locator(f'.menu[data-depth="{i}"] .mi', has=pg.locator(f'span:text-is("{label}")')).first
        if i < len(path) - 1: item.hover(); pg.wait_for_timeout(80)
        else: item.click()
    pg.wait_for_timeout(150)
def scr(pg, xy):   # sheet coordinates -> page pixels
    return pg.evaluate("""([x, y]) => { const s = document.getElementById('sch'), p = s.createSVGPoint(); p.x = x; p.y = y; const r = p.matrixTransform(s.getScreenCTM()); return [r.x, r.y]; }""", xy)
def pin_xy(pg, ref, pin):
    return pg.evaluate("""([ref, pin]) => { const st = window.__bench.current(), s = st.drawing.symbols.find(s => s.ref === ref), p = s.pins.find(q => q.name === pin);
        const svg = document.getElementById('sch'), pt = svg.createSVGPoint(); pt.x = p.x; pt.y = p.y; const r = pt.matrixTransform(svg.getScreenCTM()); return [r.x, r.y]; }""", [ref, pin])
def part_xy(pg, ref):
    b = pg.locator(f'#sch .part[data-ref="{ref}"] rect.phit').bounding_box()
    return [b['x'] + b['width'] / 2, b['y'] + b['height'] / 2]
def nets(pg):
    return pg.evaluate("() => Object.fromEntries(window.__bench.current().circuit.comps.map(c => [c.ref, c.pins]))")
def run(pg, secs=0):
    pg.keyboard.press('F5')
    pg.wait_for_function("() => /Simulating|error|problem/i.test(document.getElementById('stMsg').textContent) && window.__bench.current().sim && window.__bench.current().sim.state !== 'starting'", timeout=60000)
    if secs: pg.wait_for_timeout(int(secs * 1000))
def stop(pg):
    pg.evaluate('window.__bench.simStop()'); pg.wait_for_timeout(100)
def scope_gain(pg, ref='XSC1'):
    return pg.evaluate("""ref => { const st = window.__bench.current(), part = st.doc.parts.find(p => p.ref === ref), w = window.__bench.ctx.scopeWindow(st, part);
        if (!w || !w.ys.A || !w.ys.B) return null; const pk = a => Math.max(...a.map(Math.abs)); return pk(w.ys.B) / pk(w.ys.A); }""", ref)

